// files.ts — turn drops and pickers into the DroppedFile[] the engine eats.

import type { DroppedFile } from './parse/ingest.ts'

const TEXT_EXT = /\.(jsonl?|ndjson|txt|md|log|csv)$/i

async function walkEntry(entry: FileSystemEntry, base: string, out: { path: string; file: File }[]): Promise<void> {
  if (entry.isFile) {
    const file = await new Promise<File>((res, rej) => (entry as FileSystemFileEntry).file(res, rej))
    out.push({ path: base + file.name, file })
  } else if (entry.isDirectory) {
    const reader = (entry as FileSystemDirectoryEntry).createReader()
    const children = await new Promise<FileSystemEntry[]>((res, rej) => reader.readEntries(res, rej))
    for (const c of children) await walkEntry(c, base + entry.name + '/', out)
  }
}

/** Drop event → flat {path,text} list. Folders walked via webkit entry API. */
export async function filesFromDrop(dt: DataTransfer): Promise<DroppedFile[]> {
  const items = Array.from(dt.items ?? [])
  const entries = items.map((i) => i.webkitGetAsEntry?.()).filter(Boolean) as FileSystemEntry[]
  const flat: { path: string; file: File }[] = []
  if (entries.length) {
    for (const e of entries) await walkEntry(e, '', flat)
  } else {
    for (const f of Array.from(dt.files ?? [])) flat.push({ path: (f as File & { webkitRelativePath?: string }).webkitRelativePath || f.name, file: f })
  }
  return readAll(flat)
}

/** <input> or directory input → flat list. */
export async function filesFromInput(list: FileList | null): Promise<DroppedFile[]> {
  if (!list) return []
  const flat = Array.from(list).map((f) => ({
    path: (f as File & { webkitRelativePath?: string }).webkitRelativePath || f.name,
    file: f,
  }))
  return readAll(flat)
}

async function readAll(flat: { path: string; file: File }[]): Promise<DroppedFile[]> {
  const out: DroppedFile[] = []
  for (const { path, file } of flat) {
    if (!TEXT_EXT.test(file.name) && file.size > 0 && !file.type.startsWith('text')) continue
    if (file.size > 40 * 1024 * 1024) continue // sanity cap; sessions are text
    try {
      out.push({ path, text: await file.text() })
    } catch {
      /* unreadable — skip */
    }
  }
  return out
}

// The bundled demo export (generated by scripts/gen-demo.mjs).
const DEMO_PATHS = [
  'devin/lantern-press/nodes.jsonl',
  'devin/lantern-press/session.json',
  'codex/rollout-2026-10-09T17-20-00-palette.jsonl',
  'cursor/chat-sable/messages.jsonl',
  'cursor/chat-sable/meta.json',
  'manifest.json',
]

export async function loadDemo(): Promise<DroppedFile[]> {
  const out: DroppedFile[] = []
  for (const p of DEMO_PATHS) {
    const r = await fetch(`${import.meta.env.BASE_URL}demo/${p}`)
    if (r.ok) out.push({ path: `demo/${p}`, text: await r.text() })
  }
  return out
}
